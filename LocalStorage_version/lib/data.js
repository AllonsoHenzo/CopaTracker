export const MONTH_BR = ["","Jan","Fev","Mar","Abr","Mai","Jun","Jul","Ago","Set","Out","Nov","Dez"];
export const DOW_BR   = ["Dom","Seg","Ter","Qua","Qui","Sex","Sáb"];

export function fmtDate(d, opts = {}) {
  const dt  = new Date(d.y, d.m - 1, d.d);
  const dow = DOW_BR[dt.getDay()];
  return opts.short
    ? `${String(d.d).padStart(2,"0")} ${MONTH_BR[d.m].toUpperCase()}`
    : `${dow.toUpperCase()} ${String(d.d).padStart(2,"0")} ${MONTH_BR[d.m].toUpperCase()}`;
}

