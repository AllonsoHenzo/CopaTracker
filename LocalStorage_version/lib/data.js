function hexToRgb(hex) {
  const h = hex.replace('#', '');
  if (h.length === 3) return { r: parseInt(h[0]+h[0],16), g: parseInt(h[1]+h[1],16), b: parseInt(h[2]+h[2],16) };
  return { r: parseInt(h.slice(0,2),16), g: parseInt(h.slice(2,4),16), b: parseInt(h.slice(4,6),16) };
}

function darken(hex, amt = 0.28) {
  const { r, g, b } = hexToRgb(hex);
  return `rgb(${Math.round(r*(1-amt))},${Math.round(g*(1-amt))},${Math.round(b*(1-amt))})`;
}

function isNeutral(hex) {
  try {
    const { r, g, b } = hexToRgb(hex);
    return (r > 200 && g > 200 && b > 200) || (r < 30 && g < 30 && b < 30);
  } catch { return true; }
}

export function getTeamTheme(code) {
  const team = TEAM_BY_CODE[code];
  if (!team) return null;
  const colors = [...new Set(team.flag.filter(c => !isNeutral(c)))];
  const primary   = colors[0] || '#009739';
  const accent    = colors[1] || colors[0] || '#FEDD00';
  const secondary = colors[2] || colors[0] || '#002776';
  return {
    '--br-green':       primary,
    '--br-green-deep':  darken(primary),
    '--br-yellow':      accent,
    '--br-yellow-deep': darken(accent),
    '--br-blue':        secondary,
    '--br-blue-deep':   darken(secondary),
  };
}

export function computeStats(watchedSet, matches = MATCHES) {
  const total   = matches.length;
  const watched = matches.filter(m => watchedSet.has(m.id)).length;
  const byStage = {};
  for (const stage of Object.keys(STAGE_LABELS)) {
    const all = matches.filter(m => m.stage === stage);
    byStage[stage] = { total: all.length, watched: all.filter(m => watchedSet.has(m.id)).length };
  }
  return { total, watched, byStage };
}
