function seedRand(seed) {
  let s = seed | 0;
  return () => { s = (s * 9301 + 49297) % 233280; return s / 233280; };
}

function generateGroupMatches() {
  const matches = [];
  const rand = seedRand(20260611);
  const groupLetters = Object.keys(GROUPS);
  let id = 1;
  for (const letter of groupLetters) {
    const teams = GROUPS[letter];
    const fixtures = [[0,1],[2,3],[0,2],[1,3],[0,3],[1,2]];
    const grpIdx = groupLetters.indexOf(letter);
    const startDay = 11 + (grpIdx % 6);
    const roundDays = [startDay, startDay + 5, startDay + 10];
    fixtures.forEach((pair, fi) => {
      const round = Math.floor(fi / 2);
      const hour = fi % 2 === 0 ? "13:00" : "16:00";
      const venue = VENUES[Math.floor(rand() * VENUES.length)];
      matches.push({
        id: "G" + String(id).padStart(3, "0"),
        stage: "group", group: letter, round: round + 1,
        teams: [teams[pair[0]], teams[pair[1]]],
        date: { y: 2026, m: 6, d: roundDays[round], hh: hour },
        venue, score: null, status: "SCHEDULED",
      });
      id++;
    });
  }
  matches.sort((a, b) => a.date.d !== b.date.d ? a.date.d - b.date.d : a.date.hh.localeCompare(b.date.hh));
  return matches;
}

function generateKnockoutMatches() {
  const ko = [];
  const rand = seedRand(20260628);
  let id = 100;
  const buildRound = (stage, mm, dStart, count) => {
    for (let i = 0; i < count; i++) {
      const day = dStart + Math.floor(i / 2);
      const hour = i % 2 === 0 ? "14:00" : "18:00";
      const venue = VENUES[Math.floor(rand() * VENUES.length)];
      ko.push({ id: "K" + String(id).padStart(3,"0"), stage, round: 0, teams: ["TBD","TBD"], date: { y: 2026, m: mm, d: day, hh: hour }, venue, score: null, status: "SCHEDULED" });
      id++;
    }
  };
  buildRound("r32", 6, 28, 16);
  buildRound("r16", 7,  4,  8);
  buildRound("qf",  7,  9,  4);
  buildRound("sf",  7, 14,  2);
  buildRound("third", 7, 18, 1);
  ko.push({ id: "K200", stage: "final", round: 0, teams: ["TBD","TBD"], date: { y: 2026, m: 7, d: 19, hh: "16:00" }, venue: VENUES.find(v => v.stadium === "MetLife"), score: null, status: "SCHEDULED" });
  return ko;
}

